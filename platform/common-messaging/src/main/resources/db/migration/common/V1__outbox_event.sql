-- The transactional outbox. Every service that includes common-messaging adds this location
-- (classpath:db/migration/common) to its own Flyway config alongside its own migrations.
CREATE TABLE outbox_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(255) NOT NULL,
    aggregate_id   VARCHAR(255) NOT NULL,
    type           VARCHAR(255) NOT NULL,
    payload        JSONB        NOT NULL,
    partition_key  VARCHAR(255) NOT NULL,
    topic          VARCHAR(255) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    published_at   TIMESTAMPTZ,
    attempts       INTEGER      NOT NULL DEFAULT 0
);

-- Every poll scans exactly the unpublished rows; a partial index keeps that scan cheap as the
-- published rows accumulate.
CREATE INDEX idx_outbox_event_unpublished ON outbox_event (id) WHERE published_at IS NULL;
